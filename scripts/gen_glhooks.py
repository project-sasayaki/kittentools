#!/usr/bin/env python3
"""Generate glHooks_list.h from the glad GL header.

glad 2.x exposes every GL function as a function pointer plus a typedef that
carries the real signature (including parameter names):

    typedef <ret> (GLAD_API_PTR *PFNGLXXXPROC)(<params>);   // signature + names
    GLAD_API_CALL PFNGLXXXPROC glad_glXxx;                  // the variable
    #define glXxx glad_glXxx                                // public alias

For every GL function (from gl.h) one forwarding wrapper is emitted that calls
glad_glXxx. This keeps the interceptor in sync with whatever glad exposes;
future glad updates need no hand editing.

The ARB program upload/binding calls are excluded because glHooks.c provides
hand-written compatibility wrappers for target correction and AMD local
parameter mirroring.

GLX functions are NOT handled here. They are bridged by the hand-written
hook_GlxXxx functions in glxBridge.c, which are registered via
symbol_register("glX...", hook_..., ...) in graphics.c. glxBridge.c resolves
glX names directly from that registered table (no generated table, no
wglGetProcAddress path), so this script only deals with plain GL forwarders.

Usage:
    gen_glhooks.py <glad/gl.h> <out.h>
"""

import os
import re
import sys

EXCLUDED_GL = {
    "glProgramStringARB",
    "glProgramEnvParameter4fvARB",
    "glProgramEnvParameters4fvEXT",
    "glProgramLocalParameter4fvARB",
    "glBindProgramARB",
    "glVertex3f",
    "glNormal3f",
    "glNormal3fv",
    "glColor4ub",
    "glTexCoord2f",
    "glMultiTexCoord2fARB",
    "glClientActiveTexture",
    "glEnableClientState",
    "glDisableClientState",
    "glVertexPointer",
    "glNormalPointer",
    "glColorPointer",
    "glTexCoordPointer",
    "glBindFramebufferEXT",
    "glGenFramebuffersEXT",
    "glBindRenderbufferEXT",
    "glGenRenderbuffersEXT",
    "glDeleteRenderbuffersEXT",
    "glFramebufferRenderbufferEXT",
    "glFramebufferTexture2DEXT",
    "glRenderbufferStorageEXT",
    "glCheckFramebufferStatusEXT",
    "glDeleteFramebuffersEXT",
    "glViewport",
    "glTexImage2D",
    "glTexParameteri",
    "glTexParameterf",
    "glDeleteTextures",
    "glBindTexture",
    "glScissor",
}


def parse_gl(path):
    """Parse a glad GL header into (name, ret, params) GL entries."""
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        text = fh.read()

    # PFN typedef -> (ret, params)
    typedef_re = re.compile(
        r"typedef\s+(.+?)\s+\(GLAD_API_PTR\s+\*(\w+)\)\s*\((.*?)\)\s*;"
    )
    typedefs = {}
    for m in typedef_re.finditer(text):
        typedefs[m.group(2)] = (m.group(1).strip(), m.group(3).strip())

    # glad_glXxx variable -> PFN type
    var_re = re.compile(r"GLAD_API_CALL\s+(\w+)\s+(glad_\w+)\s*;")
    entries = []
    seen = set()
    for m in var_re.finditer(text):
        pfn, glad = m.group(1), m.group(2)
        name = glad[len("glad_"):]  # glBegin / glXChooseVisual
        if name in EXCLUDED_GL or name in seen:
            continue
        if pfn not in typedefs:
            continue
        seen.add(name)
        entries.append((name, typedefs[pfn][0], typedefs[pfn][1]))
    return entries


def split_top_params(params):
    parts, depth, cur = [], 0, ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return parts


def to_x(entry):
    name, ret, params = entry
    if params == "void" or params == "":
        return "X(%s, %s, (), ())" % (name, ret)
    plist = [p.strip() for p in split_top_params(params)]
    names = []
    for p in plist:
        # parameter name is the last whitespace-delimited identifier
        m = re.match(r"^(.*\S)\s+([A-Za-z_]\w*)\s*$", p)
        if not m:
            return None  # unnamed parameter -> drop this function
        names.append(m.group(2))
    sig = "(" + ", ".join(plist) + ")"
    args = "(" + ", ".join(names) + ")"
    return "X(%s, %s, %s, %s)" % (name, ret, sig, args)


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_glhooks.py <glad/gl.h> <out.h>\n")
        return 2
    gl_h, out = sys.argv[1:3]

    gl_entries = parse_gl(gl_h)

    # GL forwarder wrappers
    gl_lines, gl_skipped = [], 0
    for e in sorted(gl_entries, key=lambda x: x[0]):
        x = to_x(e)
        if x is None:
            gl_skipped += 1
            continue
        gl_lines.append("    " + x)

    guard = os.path.basename(out).upper().replace(".", "_")
    body_gl = " \\\n".join(gl_lines)
    content = (
        "/* Auto-generated by scripts/gen_glhooks.py. DO NOT EDIT. */\n"
        "#ifndef %s\n"
        "#define %s\n"
        "\n"
        "/* GL function forwarders (each calls glad_glXxx). */\n"
        "#define GL_HOOKS \\\n"
        "%s\n"
        "\n"
        "#endif /* %s */\n"
    ) % (guard, guard, body_gl, guard)

    with open(out, "w", encoding="utf-8") as fh:
        fh.write(content)

    sys.stderr.write(
        "gen_glhooks: wrote %d GL wrappers (%d skipped) to %s\n"
        % (len(gl_lines), gl_skipped, out)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
